import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "src", "catalog-data.ts");
const SHADED = "fluent-emoji";
const FLAT = "fluent-emoji-flat";

export const TONES = ["light", "medium-light", "medium", "medium-dark", "dark"];
const TONE_SUFFIX = /-(medium-light|medium-dark|light|medium|dark)$/;

const GROUPS = [
    ["smileys", "Smileys", ["Smileys & Emotion"]],
    ["people", "People", ["People & Body"]],
    ["animals", "Animals & nature", ["Animals & Nature"]],
    ["food", "Food & drink", ["Food & Drink"]],
    ["travel", "Travel & places", ["Travel & Places"]],
    ["activities", "Activities", ["Activities"]],
    ["objects", "Objects", ["Objects"]],
    ["symbols", "Symbols", ["Symbols", "Flags"]],
];

const readJson = (...path) =>
    JSON.parse(readFileSync(join(ROOT, "node_modules", ...path), "utf8"));

const names = (set) =>
    new Set([...Object.keys(set.icons), ...Object.keys(set.aliases ?? {})]);

const normalise = (label) =>
    label
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, "-")
        .replace(/^-+|-+$/g, "");

const capitalise = (text) => text.charAt(0).toUpperCase() + text.slice(1);

export function titleFor(name) {
    return capitalise(name.replace(/-/g, " "));
}

export function buildCatalog(shaded, flat, flatMeta, emojibase) {
    const shadedNames = names(shaded);
    const flatNames = names(flat);
    const inBoth = (name) => shadedNames.has(name) && flatNames.has(name);
    const isVariant = (name) =>
        TONE_SUFFIX.test(name) && flatNames.has(name.replace(TONE_SUFFIX, ""));
    const byLabel = new Map(emojibase.map((e) => [normalise(e.label), e]));

    const seen = new Set();
    const icons = [];
    const categories = [];
    for (const [id, title, upstream] of GROUPS) {
        const group = [];
        for (const key of upstream) {
            const listed = flatMeta.categories[key];
            if (!listed) throw new Error(`${key} is missing upstream`);
            for (const name of listed) {
                if (seen.has(name) || !inBoth(name) || isVariant(name)) {
                    continue;
                }
                seen.add(name);
                const emoji = byLabel.get(name);
                const icon = {
                    name,
                    title: emoji ? capitalise(emoji.label) : titleFor(name),
                    keywords: [...(emoji?.tags ?? []), title.toLowerCase()]
                        .join(" ")
                        .replace(/\s*&\s*/g, " "),
                };
                if (TONES.every((tone) => inBoth(`${name}-${tone}`))) {
                    icon.tones = true;
                }
                group.push({ icon, order: emoji?.order });
            }
        }
        group.sort((a, b) => {
            if (a.order !== undefined && b.order !== undefined) {
                return a.order - b.order;
            }
            if (a.order !== undefined) return -1;
            if (b.order !== undefined) return 1;
            return a.icon.name < b.icon.name ? -1 : 1;
        });
        if (group.length === 0) throw new Error(`${title} is empty`);
        icons.push(...group.map((entry) => entry.icon));
        categories.push({
            id,
            title,
            names: group.map((entry) => entry.icon.name),
        });
    }
    return { icons, categories };
}

export function readPackages() {
    return [
        readJson("@iconify-json", SHADED, "icons.json"),
        readJson("@iconify-json", FLAT, "icons.json"),
        readJson("@iconify-json", FLAT, "metadata.json"),
        readJson("emojibase-data", "en", "data.json"),
    ];
}

function source(catalog) {
    const version = (...path) => readJson(...path, "package.json").version;
    return (
        `// Generated by scripts/build-catalog.mjs from @iconify-json/${SHADED} ${version("@iconify-json", SHADED)}, @iconify-json/${FLAT} ${version("@iconify-json", FLAT)} and emojibase-data ${version("emojibase-data")}. Do not edit by hand.\n` +
        `import type { CatalogIcon, Category } from "./catalog";\n\n` +
        `export const ICONS: CatalogIcon[] = ${JSON.stringify(catalog.icons)};\n\n` +
        `export const CATEGORIES: Category[] = ${JSON.stringify(catalog.categories)};\n`
    );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    const text = source(buildCatalog(...readPackages()));
    // Skipping identical writes keeps a second build from dirtying the tree.
    if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== text) {
        writeFileSync(OUT, text);
    }
}
